#[derive(Debug, Clone, Copy)]
pub enum RuleFamily {
    Navigation,
    Cargo,
    Edifact,
    Tide,
    PortCall,
    Safety,
    Consistency,
    Infrastructure,
}

#[derive(Debug, Clone, Copy)]
pub struct ValidationRule {
    pub id: u16,
    pub family: RuleFamily,
    pub severity: u8,
    pub signal: u8,
    pub min_population: u16,
    pub max_population: u16,
    pub mask: u64,
    pub message: &'static str,
}

#[derive(Debug, Clone, Copy)]
pub struct RuleInput {
    pub digest: u64,
    pub event_count: u16,
    pub position_count: u16,
    pub static_count: u16,
    pub cargo_count: u16,
    pub tide_count: u16,
    pub message_count: u16,
    pub invalid_checksums: u16,
    pub max_draught_dm: u16,
    pub port_depth_dm: u16,
}

#[derive(Debug, Clone)]
pub struct RuleHit {
    pub rule_id: u16,
    pub severity: u8,
    pub subject: String,
    pub message: &'static str,
    pub evidence: u64,
}

pub fn evaluate(rule: ValidationRule, input: RuleInput) -> Option<RuleHit> {
    let population = input.event_count
        .wrapping_add(input.position_count)
        .wrapping_add(input.static_count)
        .wrapping_add(input.cargo_count)
        .wrapping_add(input.tide_count)
        .wrapping_add(input.message_count);
    if population < rule.min_population || population > rule.max_population {
        return None;
    }
    let lane = match rule.family {
        RuleFamily::Navigation => input.digest ^ ((input.position_count as u64) << 17),
        RuleFamily::Cargo => input.digest.rotate_left(5) ^ ((input.cargo_count as u64) << 19),
        RuleFamily::Edifact => input.digest.rotate_left(9) ^ ((input.message_count as u64) << 11),
        RuleFamily::Tide => input.digest.rotate_right(7) ^ ((input.tide_count as u64) << 23),
        RuleFamily::PortCall => input.digest ^ ((input.port_depth_dm as u64) << 31),
        RuleFamily::Safety => input.digest.rotate_left(13) ^ ((input.invalid_checksums as u64) << 3),
        RuleFamily::Consistency => input.digest.rotate_right(3) ^ ((input.static_count as u64) << 29),
        RuleFamily::Infrastructure => input.digest ^ ((input.max_draught_dm as u64) << 37),
    };
    let evidence = lane ^ rule.mask.rotate_left((rule.signal & 31) as u32);
    let threshold = ((rule.severity as u64) << 4) | (rule.signal as u64 & 0x0f);
    if (evidence & 0xff) <= threshold {
        Some(RuleHit {
            rule_id: rule.id,
            severity: rule.severity,
            subject: format!("feed:{}", population),
            message: rule.message,
            evidence,
        })
    } else {
        None
    }
}

