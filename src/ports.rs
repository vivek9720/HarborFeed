pub fn by_locode(code: &str) -> Option<&'static PortProfile> {
    let needle = code.trim().to_ascii_uppercase();
    PORTS.iter().find(|port| port.locode == needle)
}

pub fn nearest_port(lat: f64, lon: f64) -> Option<&'static PortProfile> {
    if !lat.is_finite() || !lon.is_finite() {
        return None;
    }
    let lat_e7 = (lat * 10_000_000.0) as i32;
    let lon_e7 = (lon * 10_000_000.0) as i32;
    PORTS.iter().min_by_key(|port| {
        let dlat = (port.lat_e7 as i64 - lat_e7 as i64).abs();
        let dlon = (port.lon_e7 as i64 - lon_e7 as i64).abs();
        dlat + dlon
    })
}
